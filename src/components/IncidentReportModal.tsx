import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText, Globe } from 'lucide-react';
import { Language, IncidentReport } from '../types';

interface IncidentReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: IncidentReport | null;
  caseId: string;
  language: Language;
}

export const IncidentReportModal: React.FC<IncidentReportModalProps> = ({
  isOpen,
  onClose,
  report,
  caseId,
  language,
}) => {
  const [activeTab, setActiveTab] = useState<'english' | 'hindi'>('english');
  const [copied, setCopied] = useState(false);

  if (!isOpen || !report) return null;

  const contentToDisplay = activeTab === 'english' ? report.english : report.hindi;

  const handleCopy = () => {
    navigator.clipboard.writeText(contentToDisplay);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    const printWin = window.open('', '_blank');
    if (printWin) {
      printWin.document.write(`
        <html>
          <head>
            <title>GreenGuard Incident Report - ${caseId}</title>
            <style>
              body { font-family: monospace; padding: 30px; line-height: 1.6; color: #111; }
              h1 { font-size: 18px; border-bottom: 2px solid #333; padding-bottom: 8px; }
              pre { white-space: pre-wrap; font-size: 13px; }
              .footer { margin-top: 40px; font-size: 11px; color: #666; border-top: 1px solid #ccc; padding-top: 10px; }
            </style>
          </head>
          <body>
            <h1>GREENGUARD FORESTRY INCIDENT DOSSIER</h1>
            <pre>${contentToDisplay}</pre>
            <div class="footer">Generated by GreenGuard AI · Case Ref: ${caseId} · Verification Required</div>
          </body>
        </html>
      `);
      printWin.document.close();
      printWin.focus();
      printWin.print();
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fadeIn">
      <div className="relative w-full max-w-2xl max-h-[85vh] flex flex-col bg-[#101b15] border border-[#2b4c39] rounded-2xl shadow-2xl text-[#f0fdf4] overflow-hidden">
        {/* Header */}
        <div className="p-5 border-b border-[#1e3328] flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-lg bg-[#183123] text-purple-400 border border-[#2f553f] flex items-center justify-center">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-serif-title font-bold text-lg text-white">
                  {language === 'hi' ? 'घटना विवरण प्रतिवेदन (एआई)' : 'Incident Report (Gen-AI Dossier)'}
                </h3>
                <span className="font-mono-code text-[11px] px-2 py-0.5 rounded bg-[#1f372a] text-[#c9d99f] border border-[#2f553f]">
                  {caseId.toUpperCase()}
                </span>
              </div>
              <p className="text-xs text-[#869e90]">
                {language === 'hi'
                  ? 'जेमिनी द्वारा संकलित तटस्थ, तथ्यात्मक एवं पारदर्शी सारांश'
                  : 'Factual incident summary compiled by Gemini. Non-accusatory operational record.'}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg bg-[#172820] text-[#869e90] hover:text-white hover:bg-[#20362b] transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Language Tabs & Actions */}
        <div className="px-5 py-2.5 bg-[#0b1610] border-b border-[#1e3328] flex items-center justify-between flex-wrap gap-2">
          <div className="flex items-center gap-1">
            <button
              onClick={() => setActiveTab('english')}
              className={`px-3 py-1 rounded text-xs font-semibold flex items-center gap-1.5 transition-all ${
                activeTab === 'english'
                  ? 'bg-[#213d2d] text-[#c9d99f] shadow'
                  : 'text-[#869e90] hover:text-white'
              }`}
            >
              <Globe className="w-3.5 h-3.5" /> English Dossier
            </button>
            <button
              onClick={() => setActiveTab('hindi')}
              className={`px-3 py-1 rounded text-xs font-semibold flex items-center gap-1.5 transition-all ${
                activeTab === 'hindi'
                  ? 'bg-[#213d2d] text-[#c9d99f] shadow'
                  : 'text-[#869e90] hover:text-white'
              }`}
            >
              <Globe className="w-3.5 h-3.5" /> हिन्दी प्रतिवेदन
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-2.5 py-1 rounded bg-[#14261d] border border-[#244232] text-xs text-[#869e90] hover:text-[#c9d99f] flex items-center gap-1.5 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? 'Copied' : 'Copy Text'}
            </button>
            <button
              onClick={handlePrint}
              className="px-2.5 py-1 rounded bg-[#14261d] border border-[#244232] text-xs text-[#869e90] hover:text-[#c9d99f] flex items-center gap-1.5 transition-colors"
            >
              <Printer className="w-3.5 h-3.5" /> Print
            </button>
          </div>
        </div>

        {/* Report Content Body */}
        <div className="flex-1 overflow-y-auto p-5">
          <div className="p-4 rounded-xl bg-[#0a120e] border border-[#1a2f23] text-xs font-mono-code text-[#d1e0d7] whitespace-pre-wrap leading-relaxed select-text shadow-inner">
            {contentToDisplay}
          </div>
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-[#1e3328] bg-[#0c1611] flex items-center justify-between text-xs text-[#869e90]">
          <span className="font-mono-code text-[11px]">
            Generated at: {new Date(report.generatedAt).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}
          </span>
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-lg bg-[#213b2c] hover:bg-[#2d4f3b] text-white font-medium text-xs transition-colors"
          >
            {language === 'hi' ? 'बंद करें' : 'Done'}
          </button>
        </div>
      </div>
    </div>
  );
};
